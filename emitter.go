// ReturnType represents supported C-to-Go return types.
type ReturnType string

const (
	TypeNone      ReturnType = ""
	TypeVoid      ReturnType = "void"
	TypeInt       ReturnType = "int"
	TypeInt64     ReturnType = "int64"
	TypeUint64    ReturnType = "uint64"
	TypeInt32     ReturnType = "int32"
	TypeUint32    ReturnType = "uint32"
	TypeFloat32   ReturnType = "float32"
	TypeFloat64   ReturnType = "float64"
	TypeVector128 ReturnType = "m128"
	TypeVector256 ReturnType = "m256"
)

// ReturnKind classifies a ReturnType into its low-level representation.
type ReturnKind int

const (
	RetNone ReturnKind = iota
	RetInt64
	RetInt32
	RetFloat32
	RetFloat64
	RetVector128
	RetVector256
)

// Kind returns the ReturnKind for this ReturnType.
func (rt ReturnType) Kind() ReturnKind {
	switch strings.ToLower(strings.TrimSpace(string(rt))) {
	case "void", "none":
		return RetNone
	case "", "int", "int64", "uint64", "uintptr", "pointer", "ptr", "size_t", "uint64_t", "int64_t":
		return RetInt64
	case "int32", "uint32", "int32_t", "uint32_t":
		return RetInt32
	case "float", "float32":
		return RetFloat32
	case "double", "float64":
		return RetFloat64
	case "m128", "__m128", "__m128i", "__m128d", "vec128", "vector128", "vector", "vec", "simd", "[16]byte":
		return RetVector128
	case "m256", "__m256", "__m256i", "__m256d", "vec256", "vector256", "[32]byte":
		return RetVector256
	default:
		return RetInt64
	}
}

// Size returns the stack size in bytes allocated for this return type.
func (rt ReturnType) Size() int {
	switch rt.Kind() {
	case RetNone:
		return 0
	case RetInt32, RetFloat32:
		return 4
	case RetInt64, RetFloat64:
		return 8
	case RetVector128:
		return 16
	case RetVector256:
		return 32
	default:
		return 8
	}
}

// GoType returns the corresponding Go type name.
func (rt ReturnType) GoType() string {
	switch rt.Kind() {
	case RetNone:
		return ""
	case RetInt32:
		if string(rt) == "int32" {
			return "int32"
		}
		return "uint32"
	case RetInt64:
		if string(rt) == "int64" {
			return "int64"
		}
		if string(rt) == "int" {
			return "int"
		}
		return "uint64"
	case RetFloat32:
		return "float32"
	case RetFloat64:
		return "float64"
	case RetVector128:
		return "[16]byte"
	case RetVector256:
		return "[32]byte"
	default:
		return "uint64"
	}
}

// FuncSignature describes arguments and return type for Go/Plan9 translation.
type FuncSignature struct {
	Name       string
	GoName     string
	ParamCount int        // number of 64-bit word parameters
	HasReturn  bool       // true if function returns a value
	ReturnType ReturnType // Return type: float32, float64, m128, m256, int32, int64, etc.
}

// EmitPlan9Assembly formats disassembled functions into a complete Plan 9 .s file.
func EmitPlan9Assembly(
	pkg string,
	syms []Symbol,
	sigs map[string]FuncSignature,
	rodata []byte,
	relocs []Relocation,
	arch string,
) ([]byte, error) {
	if arch == "" {
		arch = "amd64"
	}

	var buf bytes.Buffer

	buf.WriteString("// Code generated by c2plan9. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "//go:build %s && !purego\n\n", arch)
	buf.WriteString("#include \"textflag.h\"\n\n")

	if len(rodata) > 0 {
		buf.WriteString(EmitROData(rodata))
	}

	for _, sym := range syms {
		if sym.IsLocal || len(sym.Code) == 0 {
			continue
		}

		sig, hasSig := sigs[sym.Name]
		kind := RetInt64
		if hasSig && sig.ReturnType != "" {
			kind = sig.ReturnType.Kind()
		}

		var (
			res      DisassemblyResult
			err      error
			regNames []string
			loadOp   string
			storeRet string
			retReg   string
		)

		if arch == "arm64" {
			res, err = DisassembleARM64(sym.Code, sym.Offset, relocs)
			regNames = []string{"R0", "R1", "R2", "R3", "R4", "R5", "R6", "R7"}
			loadOp = "MOVD"
			switch kind {
			case RetFloat32:
				storeRet = "FMOVS"
				retReg = "F0"
			case RetFloat64:
				storeRet = "FMOVD"
				retReg = "F0"
			case RetVector128, RetVector256:
				storeRet = "FMOVQ"
				retReg = "F0"
			case RetInt32:
				storeRet = "MOVW"
				retReg = "R0"
			default:
				storeRet = "MOVD"
				retReg = "R0"
			}
		} else {
			res, err = DisassembleAMD64(sym.Code, sym.Offset, relocs)
			regNames = []string{"DI", "SI", "DX", "CX", "R8", "R9"}
			loadOp = "MOVQ"
			switch kind {
			case RetFloat32:
				storeRet = "MOVSS"
				retReg = "X0"
			case RetFloat64:
				storeRet = "MOVSD"
				retReg = "X0"
			case RetVector128:
				storeRet = "MOVOU"
				retReg = "X0"
			case RetVector256:
				storeRet = "VMOVDQU"
				retReg = "Y0"
			case RetInt32:
				storeRet = "MOVL"
				retReg = "AX"
			default:
				storeRet = "MOVQ"
				retReg = "AX"
			}
		}

		if err != nil {
			return nil, fmt.Errorf("failed to disassemble symbol %s: %w", sym.Name, err)
		}
		insts := res.Insts
		frameSize := res.FrameSize

		goName := sym.Name
		if hasSig && sig.GoName != "" {
			goName = sig.GoName
		}

		// Calculate frame and argument stack size
		paramCount := 6
		if arch == "arm64" {
			paramCount = 8
		}
		hasRet := true
		if hasSig {
			paramCount = sig.ParamCount
			hasRet = sig.HasReturn
			if kind == RetNone {
				hasRet = false
			}
		}

		retSize := 0
		if hasRet {
			retSize = 8
			if hasSig && sig.ReturnType != "" {
				retSize = sig.ReturnType.Size()
			}
		}

		argSize := paramCount*8 + retSize

		flags := "NOSPLIT"
		if frameSize > 256 {
			flags = "0"
		}

		// Emit TEXT declaration
		fmt.Fprintf(&buf, "// func %s\n", goName)
		fmt.Fprintf(&buf, "TEXT ·%s(SB), %s, $%d-%d\n", goName, flags, frameSize, argSize)

		// Emit Argument Loading Prologue
		for i := 0; i < paramCount && i < len(regNames); i++ {
			fmt.Fprintf(&buf, "\t%s arg%d+%d(FP), %s\n", loadOp, i, i*8, regNames[i])
		}

		if paramCount > 0 {
			buf.WriteString("\n")
		}

		// Emit Disassembled Instructions
		retOffset := paramCount * 8
		for _, inst := range insts {
			if inst.Label != "" {
				fmt.Fprintf(&buf, "%s:\n", inst.Label)
			}

			if inst.IsRet || strings.HasPrefix(inst.Text, "RET") || inst.Text == "LRET" {
				if hasRet {
					fmt.Fprintf(&buf, "\t%s %s, ret+%d(FP)\n", storeRet, retReg, retOffset)
				}
				buf.WriteString("\tRET\n")
			} else {
				fmt.Fprintf(&buf, "\t%s\n", inst.Text)
			}
		}

		hasTrailingRet := len(insts) > 0 && (insts[len(insts)-1].IsRet ||
			strings.HasPrefix(insts[len(insts)-1].Text, "RET") ||
			insts[len(insts)-1].Text == "LRET")
		if !hasTrailingRet {
			if hasRet {
				fmt.Fprintf(&buf, "\t%s %s, ret+%d(FP)\n", storeRet, retReg, retOffset)
			}
			buf.WriteString("\tRET\n")
		}

		buf.WriteString("\n")
	}

	return buf.Bytes(), nil
}

// EmitROData formats raw read-only data into Plan 9 DATA and GLOBL directives.
func EmitROData(rodata []byte) string {
	if len(rodata) == 0 {
		return ""
	}

	var b strings.Builder
	b.WriteString("// Static Read-Only Data (Lookup Tables & SIMD Constants)\n")

	off := 0
	n := len(rodata)
	for off < n {
		rem := n - off
		switch {
		case rem >= 8:
			v := binary.LittleEndian.Uint64(rodata[off : off+8])
			fmt.Fprintf(&b, "DATA ·rodata<>+%d(SB)/8, $0x%016x\n", off, v)
			off += 8
		case rem >= 4:
			v := binary.LittleEndian.Uint32(rodata[off : off+4])
			fmt.Fprintf(&b, "DATA ·rodata<>+%d(SB)/4, $0x%08x\n", off, v)
			off += 4
		case rem >= 2:
			v := binary.LittleEndian.Uint16(rodata[off : off+2])
			fmt.Fprintf(&b, "DATA ·rodata<>+%d(SB)/2, $0x%04x\n", off, v)
			off += 2
		default:
			v := rodata[off]
			fmt.Fprintf(&b, "DATA ·rodata<>+%d(SB)/1, $0x%02x\n", off, v)
			off++
		}
	}

	fmt.Fprintf(&b, "GLOBL ·rodata<>(SB), RODATA|NOPTR, $%d\n\n", n)
	return b.String()
}

// EmitGoStub generates companion Go stub declarations.
func EmitGoStub(pkg string, sigs []FuncSignature, arch string) []byte {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by c2plan9. DO NOT EDIT.\n\n")
	if arch == "" || arch == "all" {
		buf.WriteString("//go:build (amd64 || arm64) && !purego\n\n")
	} else {
		fmt.Fprintf(&buf, "//go:build %s && !purego\n\n", arch)
	}
	fmt.Fprintf(&buf, "package %s\n\n", pkg)
	buf.WriteString("import \"unsafe\"\n\n")
	buf.WriteString("var _ = unsafe.Pointer(nil)\n\n")

	for _, sig := range sigs {
		name := sig.GoName
		if name == "" {
			name = sig.Name
		}

		var params []string
		for i := 0; i < sig.ParamCount; i++ {
			params = append(params, fmt.Sprintf("arg%d uint64", i))
		}

		ret := ""
		if sig.HasReturn && sig.ReturnType.Kind() != RetNone {
			ret = " " + sig.ReturnType.GoType()
		}

		buf.WriteString("//go:noescape\n")
		fmt.Fprintf(&buf, "func %s(%s)%s\n\n", name, strings.Join(params, ", "), ret)
	}

	return buf.Bytes()
}
